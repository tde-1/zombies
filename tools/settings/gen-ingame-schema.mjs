#!/usr/bin/env node
// The in-game Settings tab's schema, generated from the site's catalogue.
//
// ONE SOURCE OF TRUTH. What each setting writes (dvar, values, game default, where it
// came from) is web/client/src/data/wawSettings.js; how /settings groups and names it is
// web/client/src/data/settingsLayout.js; what the in-game menu may do with it (apply
// live / vid_restart / next launch, harmless in a Verified game or not) is the INGAME
// table in wawSettings.js. This script joins the three into
// shared/settings/ingame-settings.json, which CMakeLists.txt embeds into enw_t4.dll.
// The DLL holds no list of its own.
//
//   node tools/settings/gen-ingame-schema.mjs           write the file
//   node tools/settings/gen-ingame-schema.mjs --check   exit 1 if the file is stale
//
// Tests: launcher/test/waw-settings.js runs --check's logic (buildSchema() equals the
// committed file) and the launcher's whitelist over every value a control can write.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const repo = path.resolve(here, '..', '..')
export const OUT = path.join(repo, 'shared', 'settings', 'ingame-settings.json')

const imp = (rel) => import(pathToFileURL(path.join(repo, rel)).href)

const str = (v) => (v === null || v === undefined ? '' : typeof v === 'boolean' ? (v ? '1' : '0') : String(v))

export async function buildSchema() {
  const waw = await imp('web/client/src/data/wawSettings.js')
  const layout = await imp('web/client/src/data/settingsLayout.js')
  const byId = new Map(waw.ALL.map((it) => [it.id, it]))
  const missing = waw.ALL.filter((it) => !waw.ingameOf(it)).map((it) => it.id)
  if (missing.length) throw new Error(`wawSettings.js INGAME has no policy for: ${missing.join(', ')}`)

  const items = []
  const excluded = []
  const placed = new Set()
  for (const g of layout.GROUPS) for (const id of g.items) placed.add(id)

  for (const it of waw.ALL) {
    const pol = waw.ingameOf(it)
    if (pol.apply === false) { excluded.push({ id: it.id, dvar: it.dvar || '', why: pol.why || '' }); continue }
    if (!placed.has(it.id)) { excluded.push({ id: it.id, dvar: it.dvar || '', why: 'not placed on /settings (settingsLayout.js)' }); continue }
    const o = {
      id: it.id,
      label: layout.labelOf(it),
      kind: it.kind,
      apply: pol.apply,
      verified: !!pol.verified,
    }
    if (it.kind === 'bind') {
      o.command = it.command
      o.def = it.def.slice()
    } else {
      o.dvar = pol.dvar || it.dvar || ''
      o.to = it.to
      o.def = str(it.def)
      if (it.enw !== undefined) o.enw = str(it.enw)
    }
    if (it.kind === 'toggle') {
      o.values = pol.values ? pol.values.slice() : ['0', '1']
      if (typeof it.def === 'boolean') o.def = it.def ? o.values[1] : o.values[0]
    } else if (it.kind === 'select') {
      o.values = it.options.map((x) => str(x.value))
      const words = layout.OPTION_WORDS[it.id] || {}
      o.labels = it.options.map((x) => String(words[str(x.value)] ?? x.label).toLowerCase())
    } else if (it.kind === 'mode') {
      o.kind = 'select'
      o.values = waw.COMMON_MODES.slice()
      o.labels = waw.COMMON_MODES.slice()
      o.free = true // the engine may hold a size that is not in the list; shown as is
    } else if (it.kind === 'slider') {
      o.min = it.min
      o.max = it.max
      o.step = it.step
    } else if (it.kind === 'monitor') {
      o.kind = 'info'
    }
    if (pol.apply === 'site') o.kind = 'info'
    if (pol.notBorderless) o.notBorderless = true
    if (it.also) {
      o.also = {}
      for (const [v, extra] of Object.entries(it.also)) o.also[v] = Object.entries(extra).map(([d, x]) => [d, str(x)])
    }
    const hint = layout.HINTS[it.id]
    if (hint) o.hint = hint
    items.push(o)
  }

  const kept = new Set(items.map((i) => i.id))
  const groups = layout.GROUPS
    .map((g) => ({ tab: g.tab, id: g.id, label: g.label, items: g.items.filter((id) => kept.has(id) && byId.has(id)) }))
    .filter((g) => g.items.length)
  const tabs = layout.TABS.filter((t) => groups.some((g) => g.tab === t.id)).map((t) => ({ id: t.id, label: t.label }))

  return {
    v: 1,
    about: 'GENERATED by tools/settings/gen-ingame-schema.mjs from web/client/src/data/wawSettings.js (ALL, INGAME) and settingsLayout.js. Do not edit; edit those and re-run it.',
    tabs,
    groups,
    items,
    excluded,
  }
}

export const render = (schema) => JSON.stringify(schema, null, 1) + '\n'
// The committed file as text with LF endings (core.autocrlf checks it out with CRLF on
// Windows; the content is what matters, and the DLL's JSON parser takes either).
export const readCommitted = () => fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n')

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const want = render(await buildSchema())
  if (process.argv.includes('--check')) {
    const have = fs.existsSync(OUT) ? readCommitted() : ''
    if (have !== want) {
      console.error(`${path.relative(repo, OUT)} is STALE: run node tools/settings/gen-ingame-schema.mjs`)
      process.exit(1)
    }
    console.log(`${path.relative(repo, OUT)} is current`)
  } else {
    fs.mkdirSync(path.dirname(OUT), { recursive: true })
    fs.writeFileSync(OUT, want)
    const s = JSON.parse(want)
    console.log(`wrote ${path.relative(repo, OUT)}: ${s.items.length} items in ${s.groups.length} groups on ${s.tabs.length} tabs; ${s.excluded.length} excluded (${s.excluded.map((e) => e.id).join(', ')})`)
  }
}
